from contextlib import asynccontextmanager
from pathlib import Path
from typing import List, Literal

import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, ConfigDict, Field

MODEL_PATH = Path(__file__).resolve().parent.parent / "model" / "churn_model.joblib"

_artifact = None  # populated on startup via lifespan handler


@asynccontextmanager
async def lifespan(app: FastAPI):
    global _artifact
    if not MODEL_PATH.exists():
        raise RuntimeError(
            f"Model file not found at {MODEL_PATH}. Run `python model/train.py` first."
        )
    _artifact = joblib.load(MODEL_PATH)
    yield
    _artifact = None


app = FastAPI(
    title="Customer Churn Prediction API",
    description="Predicts the probability that a telecom customer will churn, "
    "based on account and service attributes.",
    version="1.0.0",
    lifespan=lifespan,
)


