class PredictionResponse(BaseModel):
    churn_probability: float
    churn_prediction: Literal["Yes", "No"]
    risk_tier: Literal["Low", "Medium", "High"]
    threshold_used: float


def _risk_tier(prob: float) -> str:
    if prob < 0.3:
        return "Low"
    if prob < 0.6:
        return "Medium"
    return "High"


def _predict_one(features: CustomerFeatures) -> PredictionResponse:
    row = pd.DataFrame([features.model_dump()])[_artifact["feature_cols"]]
    proba = float(_artifact["pipeline"].predict_proba(row)[:, 1][0])
    threshold = _artifact["threshold"]
    return PredictionResponse(
        churn_probability=round(proba, 4),
        churn_prediction="Yes" if proba >= threshold else "No",
        risk_tier=_risk_tier(proba),
        threshold_used=threshold,
    )


@app.get("/health")
def health():
    return {"status": "ok", "model_loaded": _artifact is not None}


@app.get("/model-info")
def model_info():
    if _artifact is None:
        raise HTTPException(status_code=503, detail="Model not loaded")
    return {
        "trained_at": _artifact["trained_at"],
        "threshold": _artifact["threshold"],
        "n_features": len(_artifact["feature_cols"]),
    }


@app.post("/predict", response_model=PredictionResponse)
def predict(customer: CustomerFeatures):
    if _artifact is None:
        raise HTTPException(status_code=503, detail="Model not loaded")
    return _predict_one(customer)


@app.post("/predict/batch", response_model=List[PredictionResponse])
def predict_batch(customers: List[CustomerFeatures]):
    if _artifact is None:
        raise HTTPException(status_code=503, detail="Model not loaded")
    if len(customers) > 500:
        raise HTTPException(status_code=400, detail="Batch size limited to 500 customers per request")
    return [_predict_one(c) for c in customers]
